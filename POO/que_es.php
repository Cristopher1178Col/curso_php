/*
La Programación Orientada a Objetos (POO) es un paradigma de programación que organiza el código en torno a "objetos", que son instancias de "clases".
Estos objetos representan entidades del mundo real y permiten estructurar el código de manera más modular, reutilizable y fácil de mantener.


CONCEPTOS CLAVE DE POO

Clase:

Es una plantilla o molde que define las propiedades (atributos) y comportamientos (métodos) que tendrán los objetos.

Ejemplo: Una clase Coche puede tener atributos como color, marca y velocidad, y métodos como acelerar() o frenar().

Objeto:

Es una instancia de una clase. Representa una entidad específica.

Ejemplo: Un objeto miCoche de la clase Coche podría tener el color "rojo", la marca "Toyota" y una velocidad de 0 km/h.

Atributos:

Son las características o propiedades de un objeto.

Ejemplo: color, marca, velocidad.

Métodos:

Son las acciones o funciones que un objeto puede realizar.

Ejemplo: acelerar(), frenar().

Encapsulamiento:

Consiste en ocultar los detalles internos de un objeto y exponer solo lo necesario.

Ejemplo: Un objeto Coche puede tener un método encenderMotor() que no necesita mostrar cómo funciona internamente.

Herencia:

Permite crear nuevas clases basadas en clases existentes, reutilizando sus atributos y métodos.

Ejemplo: Una clase CocheDeportivo puede heredar de la clase Coche y añadir atributos como potencia.

Polimorfismo:

Permite que un mismo método se comporte de manera diferente según el objeto que lo invoque.

Ejemplo: Un método mover() puede funcionar de manera distinta para un Coche y un Avión.

*/

